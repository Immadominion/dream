/// Broadcaster earnings dashboard, reached from Settings → Broadcasting.
///
/// Shows the broadcaster's real USDC earnings (a revenue share of the Phoenix
/// Flight builder fees generated by their copiers' volume), an earnings event
/// history, their own Phoenix trading PnL, and a payout request action.
class BroadcasterDashboardPage extends ConsumerStatefulWidget {
  const BroadcasterDashboardPage({super.key});

  @override
  ConsumerState<BroadcasterDashboardPage> createState() =>
      _BroadcasterDashboardPageState();
}

class _BroadcasterDashboardPageState
    extends ConsumerState<BroadcasterDashboardPage> {
  BroadcasterEarnings? _earnings;
  bool _loadingEarnings = false;
  bool _requestingPayout = false;

  @override
  void initState() {
    super.initState();
    Future.microtask(_refresh);
  }

  Future<void> _refresh() async {
    setState(() => _loadingEarnings = true);
    await ref.read(copyTradingProvider.notifier).refreshMyBroadcaster();
    final earnings = await ref
        .read(copyTradingProvider.notifier)
        .fetchBroadcasterEarnings();
    if (!mounted) return;
    setState(() {
      _earnings = earnings;
      _loadingEarnings = false;
    });
  }

  Future<void> _handlePayout() async {
    if (_requestingPayout) return;
    setState(() => _requestingPayout = true);
    try {
      final amount = await ref
          .read(copyTradingProvider.notifier)
          .requestPayout();
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Payout requested: ${formatUsdc(amount)}'),
          backgroundColor: context.dreamColors.surfaceVariant,
        ),
      );
      await _refresh();
    } on PayoutException catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(e.toString()),
          backgroundColor: context.dreamColors.surfaceVariant,
        ),
      );
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Payout failed: $e'),
          backgroundColor: context.dreamColors.surfaceVariant,
        ),
      );
    } finally {
      if (mounted) setState(() => _requestingPayout = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final colors = context.dreamColors;
    final state = ref.watch(copyTradingProvider);
    final me = state.myBroadcaster;
    final isRegistered = me != null;

    return Scaffold(
      backgroundColor: colors.background,
      appBar: AppBar(
        backgroundColor: colors.background,
        elevation: 0,
        scrolledUnderElevation: 0,
        leading: IconButton(
          icon: Icon(
            PhosphorIcons.caretLeft(PhosphorIconsStyle.bold),
            color: colors.onSurface,
            size: 20.r,
          ),
          onPressed: () => Navigator.of(context).maybePop(),
        ),
        title: Text(
          'Broadcasting',
          style: TextStyle(
            color: colors.onSurface,
            fontSize: 17.sp,
            fontWeight: FontWeight.w800,
          ),
        ),
      ),
      body: RefreshIndicator(
        color: AppColors.primary,
        backgroundColor: colors.surfaceVariant,
        onRefresh: _refresh,
        child: ListView(
          padding: EdgeInsets.fromLTRB(
            20.w,
            8.h,
            20.w,
            MediaQuery.paddingOf(context).bottom + 32.h,
          ),
          children: [
            if (!isRegistered)
              _RegisterCard(
                isRegistering: state.isRegisteringBroadcaster,
                onRegister: _showRegisterSheet,
              )
            else ...[
              _EarningsHero(
                earnings: _earnings,
                loading: _loadingEarnings,
                onPayout: _handlePayout,
                requestingPayout: _requestingPayout,
              ),
              SizedBox(height: 16.h),
              _StatsGrid(earnings: _earnings),
              SizedBox(height: 22.h),
              _SectionLabel(title: 'Earnings history'),
              SizedBox(height: 12.h),
              _HistoryList(earnings: _earnings, loading: _loadingEarnings),
              SizedBox(height: 22.h),
              _EditButton(onTap: _showRegisterSheet),
            ],
          ],
        ),
      ),
    );
  }

  Future<void> _showRegisterSheet() async {
    final me = ref.read(copyTradingProvider).myBroadcaster;
    final nameCtrl = TextEditingController(text: me?.label ?? '');
    final strategyCtrl = TextEditingController(text: me?.strategy ?? '');
    final twitterCtrl = TextEditingController(text: me?.twitter ?? '');
    final colors = context.dreamColors;

    await showModalBottomSheet<void>(
      context: context,
      isScrollControlled: true,
      backgroundColor: colors.surface,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(20.r)),
      ),
      builder: (ctx) => Padding(
        padding: EdgeInsets.fromLTRB(
          20.w,
          12.h,
          20.w,
          MediaQuery.of(ctx).viewInsets.bottom + 20.h,
        ),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Center(
              child: Container(
                width: 34.w,
                height: 4.h,
                decoration: BoxDecoration(
                  color: colors.stroke,
                  borderRadius: BorderRadius.circular(100),
                ),
              ),
            ),
            SizedBox(height: 16.h),
            Text(
              me == null
                  ? 'Go live as a broadcaster'
                  : 'Edit broadcaster profile',
              style: TextStyle(
                color: colors.onSurface,
                fontSize: 18.sp,
                fontWeight: FontWeight.w800,
              ),
            ),
            SizedBox(height: 6.h),
            Text(
              'Your opens are already public on Phoenix. Register so copiers can '
              'discover you — you earn a USDC share of the trading fees their '
              'copy volume generates.',
              style: TextStyle(
                color: colors.muted,
                fontSize: 12.sp,
                height: 1.45,
              ),
            ),
            SizedBox(height: 16.h),
            _SheetField(controller: nameCtrl, label: 'Display name'),
            SizedBox(height: 10.h),
            _SheetField(controller: strategyCtrl, label: 'Strategy (optional)'),
            SizedBox(height: 10.h),
            _SheetField(controller: twitterCtrl, label: '@handle (optional)'),
            SizedBox(height: 18.h),
            SizedBox(
              width: double.infinity,
              child: ElevatedButton(
                onPressed: () async {
                  final displayName = nameCtrl.text.trim();
                  if (displayName.isEmpty) {
                    ScaffoldMessenger.of(ctx).showSnackBar(
                      SnackBar(
                        content: const Text('Display name is required.'),
                        backgroundColor: colors.surfaceVariant,
                      ),
                    );
                    return;
                  }
                  Navigator.of(ctx).pop();
                  await ref
                      .read(copyTradingProvider.notifier)
                      .registerAsBroadcaster(
                        displayName: displayName,
                        strategy: strategyCtrl.text,
                        twitter: twitterCtrl.text,
                      );
                  await _refresh();
                },
                child: Text(me == null ? 'Go live' : 'Save changes'),
              ),
            ),
          ],
        ),
      ),
    );

    nameCtrl.dispose();
    strategyCtrl.dispose();
    twitterCtrl.dispose();
  }
}


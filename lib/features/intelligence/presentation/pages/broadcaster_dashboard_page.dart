// ── Earnings hero ───────────────────────────────────────────────────────────────

class _EarningsHero extends StatelessWidget {
  final BroadcasterEarnings? earnings;
  final bool loading;
  final VoidCallback onPayout;
  final bool requestingPayout;

  const _EarningsHero({
    required this.earnings,
    required this.loading,
    required this.onPayout,
    required this.requestingPayout,
  });

  @override
  Widget build(BuildContext context) {
    final colors = context.dreamColors;
    final claimable = earnings?.claimableUsd ?? 0;
    final lifetime = earnings?.lifetimeUsd ?? 0;
    final minUsd = earnings?.payoutMinUsd ?? 5;
    final canPayout = claimable >= minUsd && !requestingPayout;

    return Container(
      padding: EdgeInsets.all(20.r),
      decoration: BoxDecoration(
        color: colors.surfaceVariant,
        borderRadius: BorderRadius.circular(16.r),
        border: Border.all(color: colors.stroke),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'Claimable',
            style: TextStyle(
              color: colors.mutedSecondary,
              fontSize: 12.sp,
              fontWeight: FontWeight.w600,
            ),
          ),
          SizedBox(height: 6.h),
          Text(
            loading && earnings == null ? '—' : formatUsdc(claimable),
            style: TextStyle(
              color: colors.onSurface,
              fontSize: 32.sp,
              fontWeight: FontWeight.w800,
              fontFeatures: const [FontFeature.tabularFigures()],
            ),
          ),
          SizedBox(height: 4.h),
          Text(
            'Lifetime earned ${formatUsdc(lifetime)}',
            style: TextStyle(color: colors.muted, fontSize: 12.sp),
          ),
          SizedBox(height: 16.h),
          SizedBox(
            width: double.infinity,
            child: ElevatedButton(
              onPressed: canPayout ? onPayout : null,
              child: requestingPayout
                  ? SizedBox(
                      width: 18.r,
                      height: 18.r,
                      child: const CircularProgressIndicator(
                        strokeWidth: 2,
                        color: Colors.white,
                      ),
                    )
                  : Text(
                      claimable >= minUsd
                          ? 'Request payout'
                          : 'Min payout ${formatUsdc(minUsd)}',
                    ),
            ),
          ),
        ],
      ),
    );
  }
}


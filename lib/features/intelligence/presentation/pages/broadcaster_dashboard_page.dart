// ── History ─────────────────────────────────────────────────────────────────────

class _HistoryList extends StatelessWidget {
  final BroadcasterEarnings? earnings;
  final bool loading;

  const _HistoryList({required this.earnings, required this.loading});

  @override
  Widget build(BuildContext context) {
    final colors = context.dreamColors;
    final history = earnings?.history ?? const [];

    if (loading && earnings == null) {
      return Padding(
        padding: EdgeInsets.symmetric(vertical: 24.h),
        child: const Center(
          child: SizedBox(
            width: 20,
            height: 20,
            child: CircularProgressIndicator(
              strokeWidth: 2,
              color: AppColors.primary,
            ),
          ),
        ),
      );
    }

    if (history.isEmpty) {
      return Container(
        width: double.infinity,
        padding: EdgeInsets.symmetric(vertical: 28.h, horizontal: 16.w),
        decoration: BoxDecoration(
          color: colors.surfaceVariant,
          borderRadius: BorderRadius.circular(12.r),
          border: Border.all(color: colors.stroke),
        ),
        child: Text(
          'No earnings yet. When someone copies your trades, the fee share '
          'lands here.',
          textAlign: TextAlign.center,
          style: TextStyle(
            color: colors.mutedSecondary,
            fontSize: 12.sp,
            height: 1.5,
          ),
        ),
      );
    }

    return Container(
      decoration: BoxDecoration(
        color: colors.surfaceVariant,
        borderRadius: BorderRadius.circular(12.r),
        border: Border.all(color: colors.stroke),
      ),
      child: Column(
        children: List.generate(history.length, (i) {
          return _HistoryRow(
            event: history[i],
            isLast: i == history.length - 1,
          );
        }),
      ),
    );
  }
}

class _HistoryRow extends StatelessWidget {
  final EarningEvent event;
  final bool isLast;

  const _HistoryRow({required this.event, required this.isLast});

  @override
  Widget build(BuildContext context) {
    final colors = context.dreamColors;
    final isPayout = event.isPayout;
    final amountColor = isPayout ? colors.warning : colors.success;
    final sign = isPayout ? '-' : '+';

    return Container(
      padding: EdgeInsets.symmetric(horizontal: 14.w, vertical: 13.h),
      decoration: BoxDecoration(
        border: isLast
            ? null
            : Border(
                bottom: BorderSide(color: colors.stroke.withValues(alpha: 0.5)),
              ),
      ),
      child: Row(
        children: [
          Container(
            width: 30.r,
            height: 30.r,
            alignment: Alignment.center,
            decoration: BoxDecoration(
              color: amountColor.withValues(alpha: 0.12),
              borderRadius: BorderRadius.circular(8.r),
            ),
            child: Icon(
              isPayout
                  ? PhosphorIcons.arrowUpRight(PhosphorIconsStyle.bold)
                  : PhosphorIcons.coins(PhosphorIconsStyle.bold),
              size: 14.r,
              color: amountColor,
            ),
          ),
          SizedBox(width: 12.w),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  isPayout
                      ? 'Payout requested'
                      : '${event.market ?? 'Copy'} ${event.side ?? ''}'.trim(),
                  style: TextStyle(
                    color: colors.onSurface,
                    fontSize: 13.sp,
                    fontWeight: FontWeight.w700,
                  ),
                ),
                SizedBox(height: 2.h),
                Text(
                  _formatTime(event.timestamp),
                  style: TextStyle(
                    color: colors.mutedSecondary,
                    fontSize: 11.sp,
                  ),
                ),
              ],
            ),
          ),
          Text(
            '$sign${formatUsdc(event.earnedUsd.abs())}',
            style: TextStyle(
              color: amountColor,
              fontSize: 13.sp,
              fontWeight: FontWeight.w800,
              fontFeatures: const [FontFeature.tabularFigures()],
            ),
          ),
        ],
      ),
    );
  }

  static String _formatTime(DateTime t) {
    final now = DateTime.now();
    final diff = now.difference(t);
    if (diff.inMinutes < 1) return 'just now';
    if (diff.inMinutes < 60) return '${diff.inMinutes}m ago';
    if (diff.inHours < 24) return '${diff.inHours}h ago';
    if (diff.inDays < 7) return '${diff.inDays}d ago';
    return '${t.day}/${t.month}/${t.year}';
  }
}

